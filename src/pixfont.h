/* Columns for one character, with everything unprintable folded onto '?'. */
static inline const uint8_t *cp_font_glyph(int ch)
{
    if (ch < 0x20 || ch > 0x7F) ch = '?';
    return CP_FONT[ch - 0x20];
}

/* Advance is six columns: five of glyph and one of gap. */
static inline int cp_font_width(const char *s, int sc)
{
    return (int)strlen(s) * 6 * sc;
}

